#!/usr/bin/env python3
"""Decision Tracker build step.

Scans a folder of decision nodes (each `nodes/<id-slug>/node.md` with YAML
frontmatter) and renders two views:

  - index.md   : an auto-generated table of all nodes.
  - graph.html : a single self-contained interactive viewer (directed graph,
                 click a node to read its markdown).

Run once:   uv run python src/decision-tracker/build.py
Watch:      uv run python src/decision-tracker/build.py --watch

The graph is *directed*; cycles are allowed. Validation is intentionally light
so a half-written graph still renders: problems are warnings, not hard errors.
"""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
import time
from datetime import datetime
from pathlib import Path

import yaml

# Data root: <repo>/docs/decisions  (repo = two levels above this file).
# The authored nodes and index.md are git-tracked; graph.html is generated and ignored.
DEFAULT_ROOT = Path(__file__).resolve().parents[2] / "docs" / "decisions"

# Status -> display color. Unknown statuses fall back to the "open" color.
STATUS_COLORS = {
    "worked": "#3fb950",
    "failed": "#f85149",
    "open": "#58a6ff",
    "superseded": "#d29922",
}
STATUS_ORDER = ["worked", "open", "failed", "superseded"]

FRONTMATTER_RE = re.compile(r"^---\s*\n(.*?)\n---\s*\n?(.*)$", re.DOTALL)


# --------------------------------------------------------------------------- #
# Parsing
# --------------------------------------------------------------------------- #
def parse_node(node_md: Path) -> dict:
    """Parse one node.md into a dict of metadata + body. Missing fields default."""
    text = node_md.read_text(encoding="utf-8")
    m = FRONTMATTER_RE.match(text)
    if m:
        meta = yaml.safe_load(m.group(1)) or {}
        body = m.group(2)
    else:
        meta, body = {}, text

    folder = node_md.parent
    # id defaults to the folder prefix before the first '-' (e.g. D002-slug -> D002).
    node_id = str(meta.get("id") or folder.name.split("-", 1)[0]).strip()
    parents = meta.get("parents") or []
    if isinstance(parents, str):
        parents = [parents]

    node = {
        "id": node_id,
        "title": str(meta.get("title") or node_id),
        "parents": [str(p).strip() for p in parents],
        "status": str(meta.get("status") or "open").strip(),
        "date": str(meta.get("date") or ""),
        "tags": meta.get("tags") or [],
        "folder": folder.name,      # relative to nodes/, used to resolve assets
        "body": body,
    }
    # Carry any extra frontmatter keys through untouched (future flexibility).
    for k, v in meta.items():
        node.setdefault(k, v)
    return node


def load_nodes(root: Path) -> tuple[list[dict], list[str]]:
    """Load every nodes/*/node.md. Returns (nodes, warnings)."""
    nodes_dir = root / "nodes"
    nodes, warnings = [], []
    seen: dict[str, str] = {}

    for node_md in sorted(nodes_dir.glob("*/node.md")):
        try:
            node = parse_node(node_md)
        except Exception as e:  # noqa: BLE001 - keep building despite one bad file
            warnings.append(f"{node_md}: failed to parse ({e})")
            continue
        if node["id"] in seen:
            warnings.append(
                f"duplicate id {node['id']!r} in {node['folder']} "
                f"(already used by {seen[node['id']]}); skipping"
            )
            continue
        seen[node["id"]] = node["folder"]
        nodes.append(node)

    ids = {n["id"] for n in nodes}
    for n in nodes:
        for p in n["parents"]:
            if p not in ids:
                warnings.append(
                    f"{n['id']}: parent {p!r} does not exist; edge dropped"
                )
    return nodes, warnings


# --------------------------------------------------------------------------- #
# Rendering
# --------------------------------------------------------------------------- #
def write_index(root: Path, nodes: list[dict]) -> None:
    lines = [
        "# Decision Index",
        "",
        "_Auto-generated by build.py — do not edit._",
        "",
        f"{len(nodes)} decisions. Open `graph.html` for the interactive view.",
        "",
        "| id | title | status | parents | link |",
        "| -- | ----- | ------ | ------- | ---- |",
    ]
    for n in sorted(nodes, key=lambda x: x["id"]):
        parents = ", ".join(n["parents"]) or "—"
        link = f"[node.md](nodes/{n['folder']}/node.md)"
        lines.append(
            f"| {n['id']} | {n['title']} | {n['status']} | {parents} | {link} |"
        )
    lines.append("")
    (root / "index.md").write_text("\n".join(lines), encoding="utf-8")


def build_graph_data(nodes: list[dict]) -> dict:
    ids = {n["id"] for n in nodes}
    cy_nodes = [
        {
            "data": {
                "id": n["id"],
                "nid": n["id"],
                "title": n["title"],                            # used for search
                # Full title packed into the node; box auto-grows to fit it.
                "label": f"{n['id']}  {' '.join(n['title'].split())}",
                "status": n["status"],
                "color": STATUS_COLORS.get(n["status"], STATUS_COLORS["open"]),
            }
        }
        for n in nodes
    ]
    cy_edges = [
        {"data": {"id": f"{p}->{n['id']}", "source": p, "target": n["id"]}}
        for n in nodes
        for p in n["parents"]
        if p in ids
    ]
    # Per-node payload for the side panel (raw markdown + folder for asset paths).
    payload = {
        n["id"]: {
            "title": n["title"],
            "status": n["status"],
            "date": n["date"],
            "tags": n["tags"],
            "parents": n["parents"],
            "folder": n["folder"],
            "body": n["body"],
        }
        for n in nodes
    }
    return {"elements": cy_nodes + cy_edges, "payload": payload}


def write_graph_html(root: Path, nodes: list[dict], stamp: str) -> None:
    data = build_graph_data(nodes)
    legend = "".join(
        f'<span class="chip"><i style="background:{STATUS_COLORS[s]}"></i>{s}</span>'
        for s in STATUS_ORDER
    )
    html_doc = (
        HTML_TEMPLATE
        .replace("%%DATA%%", json.dumps(data))
        .replace("%%STAMP%%", html.escape(stamp))
        .replace("%%LEGEND%%", legend)
        .replace("%%COUNT%%", str(len(nodes)))
    )
    (root / "graph.html").write_text(html_doc, encoding="utf-8")


def build(root: Path, quiet: bool = False) -> None:
    nodes, warnings = load_nodes(root)
    stamp = datetime.now().isoformat(timespec="seconds")
    write_index(root, nodes)
    write_graph_html(root, nodes, stamp)
    (root / ".build-stamp").write_text(stamp, encoding="utf-8")
    if not quiet:
        print(f"[{stamp}] built {len(nodes)} nodes -> index.md, graph.html")
        for w in warnings:
            print(f"  warning: {w}")


# --------------------------------------------------------------------------- #
# Watch mode
# --------------------------------------------------------------------------- #
def watch(root: Path) -> None:
    from watchdog.events import FileSystemEventHandler
    from watchdog.observers import Observer

    build(root)
    print(f"watching {root / 'nodes'} for changes … (Ctrl-C to stop)")

    state = {"pending": False, "last": 0.0}

    class Handler(FileSystemEventHandler):
        def on_any_event(self, event):
            if event.is_directory:
                return
            state["pending"] = True
            state["last"] = time.time()

    observer = Observer()
    observer.schedule(Handler(), str(root / "nodes"), recursive=True)
    observer.start()
    try:
        while True:
            time.sleep(0.3)
            # Debounce: rebuild ~0.4s after the last change settles.
            if state["pending"] and (time.time() - state["last"]) > 0.4:
                state["pending"] = False
                try:
                    build(root)
                except Exception as e:  # noqa: BLE001
                    print(f"  build error: {e}", file=sys.stderr)
    except KeyboardInterrupt:
        pass
    finally:
        observer.stop()
        observer.join()


def main() -> None:
    ap = argparse.ArgumentParser(description="Build the decision tracker views.")
    ap.add_argument("--root", type=Path, default=DEFAULT_ROOT,
                    help=f"data root (default: {DEFAULT_ROOT})")
    ap.add_argument("--watch", action="store_true", help="rebuild on file changes")
    args = ap.parse_args()
    args.root.mkdir(parents=True, exist_ok=True)
    (args.root / "nodes").mkdir(exist_ok=True)
    if args.watch:
        watch(args.root)
    else:
        build(args.root)


